"""The LangGraph agent: safety -> extract -> route -> search / ask for location / explain / decline.

    safety ─▶ extract ─┬─▶ search ──────▶ END
                        ├─▶ ask_location ─▶ END
                        ├─▶ explain ─────▶ END
                        ├─▶ decline ─────▶ END
                        └─▶ fallback ────▶ END   (extraction failed)

Listings always come from the database; answer texts are fixed templates, so nothing about a facility is
ever generated by the LLM.
"""

import re
from collections.abc import Callable
from functools import lru_cache
from typing import TypedDict

from langgraph.graph import END, START, StateGraph

from .. import repository
from ..models import FacilitySearch
from .prompts import TEMPLATES
from .safety import is_emergency

PINCODE = re.compile(r"(?<!\d)([1-9]\d{5})(?!\d)")
DEVANAGARI = re.compile(r"[\u0900-\u097F]")


class State(TypedDict, total=False):
    question: str
    lat: float | None
    lon: float | None
    emergency: bool
    filters: FacilitySearch
    failed: bool
    results: list[dict]
    answer: str
    needs_location: bool
    sources: list[str]


def _language(state: State) -> str:
    f = state.get("filters")
    if DEVANAGARI.search(state["question"]):
        return "hi"
    return f.language if f else "en"


def _prefix(state: State) -> str:
    return TEMPLATES[_language(state)]["emergency"] + " " if state.get("emergency") else ""


def build_graph(
    extract_fn: Callable[[str], FacilitySearch] | None = None,
    search_fn: Callable[..., list[dict]] | None = None,
    explain_fn: Callable[[str, str], tuple[str, list[str]]] | None = None,
):
    """Build the graph. The three functions can be swapped for fakes in tests."""
    if extract_fn is None:

        def extract_fn(question: str) -> FacilitySearch:
            from .llm import extractor

            return extractor().invoke({"question": question})

    if explain_fn is None:
        from .glossary import explain_term as explain_fn
    search_fn = search_fn or repository.search

    def safety(s: State):
        return {"emergency": is_emergency(s["question"])}

    def extract(s: State):
        try:
            f = extract_fn(s["question"])
        except Exception:
            # The emergency answer must still work when the LLM is unavailable.
            f, failed = FacilitySearch(intent="find"), True
        else:
            failed = False
        update: dict = {}
        if not f.pincode and (m := PINCODE.search(s["question"])):
            update["pincode"] = m.group(1)  # never lose a pincode the user typed
        if s["emergency"]:
            update.update(intent="emergency", facility_type="hospital", emergency_only=True)
        if DEVANAGARI.search(s["question"]):
            update["language"] = "hi"
        return {"filters": f.model_copy(update=update), "failed": failed and not s["emergency"]}

    def route(s: State) -> str:
        f = s["filters"]
        if s.get("failed"):
            return "fallback"
        if f.intent == "explain":
            return "explain"
        if f.intent == "out_of_scope":
            return "decline"
        has_place = bool(f.city or f.pincode) or s.get("lat") is not None
        return "search" if has_place else "ask_location"

    def search(s: State):
        f, t = s["filters"], TEMPLATES[_language(s)]
        rows = search_fn(f, s.get("lat"), s.get("lon"))
        if not rows and s.get("emergency"):
            # Emergency data is often missing: show any nearby hospital rather than nothing.
            rows = search_fn(f.model_copy(update={"emergency_only": False}), s.get("lat"), s.get("lon"))
            msg = t["found_fallback"].format(n=len(rows)) if rows else t["none"]
        else:
            msg = t["found"].format(n=len(rows)) if rows else t["none"]
        return {"results": rows, "answer": _prefix(s) + msg}

    def ask_location(s: State):
        return {"needs_location": True, "answer": _prefix(s) + TEMPLATES[_language(s)]["where"]}

    def explain(s: State):
        try:
            text, sources = explain_fn(s["question"], _language(s))
        except Exception:
            return {"answer": TEMPLATES[_language(s)]["error"]}
        return {"answer": text, "sources": sources}

    def decline(s: State):
        return {"answer": _prefix(s) + TEMPLATES[_language(s)]["decline"]}

    def fallback(s: State):
        return {"answer": TEMPLATES[_language(s)]["error"]}

    g = StateGraph(State)
    nodes = {
        "safety": safety,
        "extract": extract,
        "search": search,
        "ask_location": ask_location,
        "explain": explain,
        "decline": decline,
        "fallback": fallback,
    }
    for name, fn in nodes.items():
        g.add_node(name, fn)
    g.add_edge(START, "safety")
    g.add_edge("safety", "extract")
    g.add_conditional_edges("extract", route, ["search", "ask_location", "explain", "decline", "fallback"])
    for name in ["search", "ask_location", "explain", "decline", "fallback"]:
        g.add_edge(name, END)
    return g.compile()


@lru_cache
def get_graph():
    return build_graph()


def ask(question: str, lat: float | None = None, lon: float | None = None) -> dict:
    out = get_graph().invoke({"question": question, "lat": lat, "lon": lon})
    return {
        "answer": out.get("answer", ""),
        "results": out.get("results", []),
        "needs_location": out.get("needs_location", False),
        "emergency": out.get("emergency", False),
        "sources": out.get("sources", []),
    }
